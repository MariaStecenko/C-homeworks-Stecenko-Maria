#include <iostream>

using namespace std;

int main() {
    // Ініціалізація дійсної матриці 3x3
    double matrix[3][3] = {
        {1.0, 2.3, 3.0},
        {4.0, 5.0, 6.0},
        {7.0, 8.0, 9.0}
    };

    int i, j;
    double a;

    // Введення натуральних чисел i, j (розглядаємо нумерацію від 1 до 3)
    cout << "Введіть номер рядка i (1-3): ";
    cin >> i;
    cout << "Введіть номер стовпця j (1-3): ";
    cin >> j;
    cout << "Введіть нове дійсне число a: ";
    cin >> a;

    // Переведення з 1-базової системи (1..3) у 0-базову для C++ (0..2)
    int row = i - 1;
    int col = j - 1;

    // Перевірка коректності індексів
    if (row >= 0 && row < 3 && col >= 0 && col < 3) {
        matrix[row][col] = a;

        cout << "\nОтримана матриця:" << endl;
        for (int r = 0; r < 3; r++) {
            for (int c = 0; c < 3; c++) {
                cout << matrix[r][c] << "\t";
            }
            cout << endl;
        }
    } else {
        cout << "\nПомилка: індекси виходять за межі матриці 3x3!" << endl;
    }

    return 0;
}
